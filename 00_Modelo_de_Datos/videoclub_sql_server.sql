/* ============================================================
   1. ESQUEMA — CREACIÓN DE TABLAS
   ============================================================ */

CREATE TABLE Pais (
    pais_id INT IDENTITY(1,1) PRIMARY KEY,
    nombre NVARCHAR(60) NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Ciudad (
    ciudad_id INT IDENTITY(1,1) PRIMARY KEY,
    nombre NVARCHAR(60) NOT NULL,
    pais_id INT NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Ciudad_Pais FOREIGN KEY (pais_id) REFERENCES Pais(pais_id)
);

CREATE TABLE Direccion (
    direccion_id INT IDENTITY(1,1) PRIMARY KEY,
    direccion NVARCHAR(100) NOT NULL,
    direccion2 NVARCHAR(100) NULL,
    distrito NVARCHAR(60) NOT NULL,
    ciudad_id INT NOT NULL,
    codigo_postal NVARCHAR(10) NULL,
    telefono NVARCHAR(20) NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Direccion_Ciudad FOREIGN KEY (ciudad_id) REFERENCES Ciudad(ciudad_id)
);

CREATE TABLE Categoria (
    categoria_id INT IDENTITY(1,1) PRIMARY KEY,
    nombre NVARCHAR(30) NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Idioma (
    idioma_id INT IDENTITY(1,1) PRIMARY KEY,
    nombre NVARCHAR(30) NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Actor (
    actor_id INT IDENTITY(1,1) PRIMARY KEY,
    nombre NVARCHAR(50) NOT NULL,
    apellido NVARCHAR(50) NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Pelicula (
    pelicula_id INT IDENTITY(1,1) PRIMARY KEY,
    titulo NVARCHAR(150) NOT NULL,
    descripcion NVARCHAR(500) NULL,
    anio_lanzamiento INT NOT NULL,
    idioma_id INT NOT NULL,
    duracion_alquiler_dias INT NOT NULL,       -- días permitidos de alquiler
    tarifa_alquiler DECIMAL(6,2) NOT NULL,      -- costo de alquilarla
    duracion_minutos INT NOT NULL,
    costo_reemplazo DECIMAL(7,2) NOT NULL,
    clasificacion NVARCHAR(10) NOT NULL,        -- ATP, +13, +16, +18
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Pelicula_Idioma FOREIGN KEY (idioma_id) REFERENCES Idioma(idioma_id)
);

CREATE TABLE Pelicula_Actor (
    pelicula_id INT NOT NULL,
    actor_id INT NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_Pelicula_Actor PRIMARY KEY (pelicula_id, actor_id),
    CONSTRAINT FK_PA_Pelicula FOREIGN KEY (pelicula_id) REFERENCES Pelicula(pelicula_id),
    CONSTRAINT FK_PA_Actor FOREIGN KEY (actor_id) REFERENCES Actor(actor_id)
);

CREATE TABLE Pelicula_Categoria (
    pelicula_id INT NOT NULL,
    categoria_id INT NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_Pelicula_Categoria PRIMARY KEY (pelicula_id, categoria_id),
    CONSTRAINT FK_PC_Pelicula FOREIGN KEY (pelicula_id) REFERENCES Pelicula(pelicula_id),
    CONSTRAINT FK_PC_Categoria FOREIGN KEY (categoria_id) REFERENCES Categoria(categoria_id)
);

CREATE TABLE Sucursal (
    sucursal_id INT IDENTITY(1,1) PRIMARY KEY,
    nombre NVARCHAR(60) NOT NULL,
    direccion_id INT NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Sucursal_Direccion FOREIGN KEY (direccion_id) REFERENCES Direccion(direccion_id)
);

CREATE TABLE Personal (
    personal_id INT IDENTITY(1,1) PRIMARY KEY,
    nombre NVARCHAR(50) NOT NULL,
    apellido NVARCHAR(50) NOT NULL,
    direccion_id INT NOT NULL,
    email NVARCHAR(100) NULL,
    sucursal_id INT NOT NULL,
    activo BIT NOT NULL DEFAULT 1,
    usuario NVARCHAR(30) NOT NULL,
    clave NVARCHAR(100) NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Personal_Direccion FOREIGN KEY (direccion_id) REFERENCES Direccion(direccion_id),
    CONSTRAINT FK_Personal_Sucursal FOREIGN KEY (sucursal_id) REFERENCES Sucursal(sucursal_id)
);

CREATE TABLE Cliente (
    cliente_id INT IDENTITY(1,1) PRIMARY KEY,
    nombre NVARCHAR(50) NOT NULL,
    apellido NVARCHAR(50) NOT NULL,
    email NVARCHAR(100) NULL,
    direccion_id INT NOT NULL,
    sucursal_id INT NOT NULL,
    activo BIT NOT NULL DEFAULT 1,
    fecha_alta DATE NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Cliente_Direccion FOREIGN KEY (direccion_id) REFERENCES Direccion(direccion_id),
    CONSTRAINT FK_Cliente_Sucursal FOREIGN KEY (sucursal_id) REFERENCES Sucursal(sucursal_id)
);

CREATE TABLE Inventario (
    inventario_id INT IDENTITY(1,1) PRIMARY KEY,
    pelicula_id INT NOT NULL,
    sucursal_id INT NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Inventario_Pelicula FOREIGN KEY (pelicula_id) REFERENCES Pelicula(pelicula_id),
    CONSTRAINT FK_Inventario_Sucursal FOREIGN KEY (sucursal_id) REFERENCES Sucursal(sucursal_id)
);

CREATE TABLE Alquiler (
    alquiler_id INT IDENTITY(1,1) PRIMARY KEY,
    fecha_alquiler DATETIME NOT NULL,
    inventario_id INT NOT NULL,
    cliente_id INT NOT NULL,
    fecha_devolucion DATETIME NULL,
    personal_id INT NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Alquiler_Inventario FOREIGN KEY (inventario_id) REFERENCES Inventario(inventario_id),
    CONSTRAINT FK_Alquiler_Cliente FOREIGN KEY (cliente_id) REFERENCES Cliente(cliente_id),
    CONSTRAINT FK_Alquiler_Personal FOREIGN KEY (personal_id) REFERENCES Personal(personal_id)
);

CREATE TABLE Pago (
    pago_id INT IDENTITY(1,1) PRIMARY KEY,
    cliente_id INT NOT NULL,
    personal_id INT NOT NULL,
    alquiler_id INT NOT NULL,
    monto DECIMAL(6,2) NOT NULL,
    fecha_pago DATETIME NOT NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT GETDATE(),
    CONSTRAINT FK_Pago_Cliente FOREIGN KEY (cliente_id) REFERENCES Cliente(cliente_id),
    CONSTRAINT FK_Pago_Personal FOREIGN KEY (personal_id) REFERENCES Personal(personal_id),
    CONSTRAINT FK_Pago_Alquiler FOREIGN KEY (alquiler_id) REFERENCES Alquiler(alquiler_id)
);
GO

/* Índices para acelerar los JOINs y agregaciones más comunes */
CREATE INDEX IX_Alquiler_Cliente ON Alquiler(cliente_id);
CREATE INDEX IX_Alquiler_Inventario ON Alquiler(inventario_id);
CREATE INDEX IX_Pago_Cliente ON Pago(cliente_id);
CREATE INDEX IX_Inventario_Pelicula ON Inventario(pelicula_id);
CREATE INDEX IX_Pelicula_Titulo ON Pelicula(titulo);
GO

